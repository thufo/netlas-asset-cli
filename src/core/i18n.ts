const translations: Record<Language, Record<TranslationKey, string>> = { en, "zh-CN": zhCN, ru };

export function resolveLanguage(locale?: string): Language {
  const normalized = (locale || "").replace("_", "-").toLowerCase();
  if (normalized.startsWith("zh")) return "zh-CN";
  if (normalized.startsWith("ru")) return "ru";
  return "en";
}

export function translate(language: Language, key: TranslationKey, values: Record<string, string | number> = {}): string {
  let message = translations[language][key] ?? en[key];
  for (const [name, value] of Object.entries(values)) {
    message = message.replaceAll(`{${name}}`, String(value));
  }
  return message;
}

export function getTranslations(language: Language): Record<TranslationKey, string> {
  return { ...translations[language] };
}

